  d.ellipse((cx-s*.3,cy-s*.3,cx+s*.3,cy+s*.3),outline=(115,194,191,255),width=max(2,int(s*.06)));d.line((cx,cy,cx+s*.19,cy-s*.13),fill='white',width=max(2,int(s*.06)));return im
